import type { VocabCategory, Word } from '@/types'

/** [english, russian, emoji (or #hex colour swatch), IPA, example, example in Russian] */
type Row = [string, string, string, string, string, string]

const slug = (s: string) => s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/(^-|-$)/g, '')

function category(id: string, title: string, titleRu: string, emoji: string, description: string, rows: Row[]): VocabCategory {
  return {
    id,
    title,
    titleRu,
    emoji,
    description,
    words: rows.map(([en, ru, e, ipa, example, exampleRu]) => ({
      id: `${id}-${slug(en)}`,
      en,
      ru,
      emoji: e,
      ipa,
      example,
      exampleRu,
      category: id,
    })),
  }
}

