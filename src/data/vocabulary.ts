export const PICTURE_CATEGORIES = new Set(['numbers', 'colors', 'jobs', 'countries', 'school', 'food', 'home', 'clothes', 'weather', 'animals', 'transport', 'hobbies'])

export const ALL_WORDS: Word[] = VOCAB_CATEGORIES.flatMap((c) => c.words)

const BY_ID = new Map(ALL_WORDS.map((w) => [w.id, w]))

export function getWord(id: string): Word | undefined {
  return BY_ID.get(id)
}

export function getWords(ids: string[]): Word[] {
  return ids.map((id) => BY_ID.get(id)).filter((w): w is Word => !!w)
}

export function getCategory(id: string): VocabCategory | undefined {
  return VOCAB_CATEGORIES.find((c) => c.id === id)
}
